# ======================================================================================
# Insertion Sort (Ascending)
# ======================================================================================

def insertionSort_asc(data):
    for i in range(1, len(data)):
        key = data[i]
        j = i - 1
        while j >= 0 and key < data[j]:
            data[j + 1] = data[j]
            j -= 1
        data[j + 1] = key

data = [54,26,93,17,77,31,44,55,20]
insertionSort_asc(data)
print(data)